local describe = require('devtools.tests.define.describe')
local should = require('devtools.tests.should')
local only = require('devtools.tests.define.only')
local skip = require('devtools.tests.define.skip')

local Timer = require('devtools.logs.timer')

describe('Timer', function()
    describe("captures_log", function()
        it("include overall + captures", function()
            local t = Timer.new()
            t:capture("first")
            t:capture("second")

            local log_output = t:captures_log()

            assert.matches("Overall time: %d*", log_output)
            assert.matches("  first: %d*", log_output)
            assert.matches("  second: %d*", log_output)
        end)
    end)

    describe('format_elapsed_time', function()
        it("formats in minutes when elapsed_seconds >= 60s", function()
            should.be_equal('1.0min', Timer.format_elapsed_time(60))
            should.be_equal('2.2min', Timer.format_elapsed_time(131))
        end)

        it('formats seconds when elapsed_seconds >= 1s', function()
            should.be_equal('1.0s', Timer.format_elapsed_time(1.0))
            should.be_equal('1.2s', Timer.format_elapsed_time(1.2345))
            should.be_equal('2.4s', Timer.format_elapsed_time(2.3556))
        end)

        it('formats milliseconds from 1ms => 1000ms', function()
            should.be_equal('1.0ms', Timer.format_elapsed_time(0.001))
            should.be_equal('5.0ms', Timer.format_elapsed_time(0.005))
            should.be_equal('10.0ms', Timer.format_elapsed_time(0.010))
            should.be_equal('20.1ms', Timer.format_elapsed_time(0.02014))
            should.be_equal('20.2ms', Timer.format_elapsed_time(0.02015))
        end)

        it('formats microseconds when from 1us => 1000us', function()
            should.be_equal('500µs', Timer.format_elapsed_time(0.0005))
            should.be_equal('1µs', Timer.format_elapsed_time(0.000001))
        end)

        it('formats nanoseconds when < 1us', function()
            should.be_equal('500ns', Timer.format_elapsed_time(0.0000005))
            should.be_equal('1ns', Timer.format_elapsed_time(0.000000001))
            should.be_equal('1ns', Timer.format_elapsed_time(0.00000000075))
        end)
    end)
end)
